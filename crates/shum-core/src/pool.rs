//! The shared set of reactions and stickers drawn in Shum's pixels: the
//! design's 45 pictures, emoji at 16 x 16 and characters at 32 x 32, one
//! cell a point. Every client draws them from here.
use crate::packet::ReactionKind;

/// A part of the set, as clients group it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Section {
    Emoji,
    Crab,
    Cat,
    Bun,
    Frog,
}

impl Section {
    /// Its name in the protocol and for clients.
    pub fn name(self) -> &'static str {
        match self {
            Section::Emoji => "emoji",
            Section::Crab => "crab",
            Section::Cat => "cat",
            Section::Bun => "bun",
            Section::Frog => "frog",
        }
    }
}

