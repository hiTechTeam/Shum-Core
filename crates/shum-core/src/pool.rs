/// The picture as RGBA bytes, row by row, and its side in pixels.
pub fn rgba(kind: ReactionKind) -> (usize, Vec<u8>) {
    let (rows, colors) = art(kind);
    let pixels = rows
        .iter()
        .flat_map(|row| row.bytes())
        .flat_map(|symbol| {
            colors
                .iter()
                .find(|(s, _)| *s == symbol)
                .map(|(_, rgb)| [(rgb >> 16) as u8, (rgb >> 8) as u8, *rgb as u8, 255])
                .unwrap_or([0; 4])
        })
        .collect();
    (rows.len(), pixels)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_picture_is_square_and_drawn() {
        for kind in ORDER {
            let (rows, colors) = art(kind);
            let side = if section(kind) == Section::Emoji {
                16
            } else {
                32
            };
            assert_eq!(rows.len(), side, "{kind:?}");
            for row in rows {
                assert_eq!(row.len(), side, "{kind:?}");
                for symbol in row.bytes().filter(|s| *s != b'.') {
                    assert!(colors.iter().any(|(s, _)| *s == symbol), "{kind:?}");
                }
            }
            let (size, pixels) = rgba(kind);
            assert_eq!(pixels.len(), size * size * 4);
            assert!(pixels.chunks(4).any(|p| p[3] == 255), "{kind:?} is empty");
        }
    }

    #[test]
    fn the_set_has_each_reaction_once() {
        let mut seen = std::collections::HashSet::new();
        assert!(ORDER.iter().all(|k| seen.insert(*k)));
        assert_eq!(
            rgba(ReactionKind::Heart).1[..4],
            [0, 0, 0, 0],
            "transparent corner"
        );
    }
}
