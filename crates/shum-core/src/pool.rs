/// Which part of the set a reaction belongs to.
pub fn section(kind: ReactionKind) -> Section {
    use ReactionKind::*;
    match kind {
        CrabLyublyu | CrabObnimayu | CrabPlachu | CrabShok | CrabUra | CrabIcon => Section::Crab,
        CatLyublyu | CatRyba | CatEda | CatKorobka | CatTygydyk | CatShshsh | CatBuhanka
        | CatUps | CatIcon => Section::Cat,
        BunZlyus | BunPlachu | BunIcon => Section::Bun,
        FrogIcon => Section::Frog,
        _ => Section::Emoji,
    }
}

